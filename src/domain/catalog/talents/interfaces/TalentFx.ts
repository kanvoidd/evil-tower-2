import type { TalentBonusFx } from './TalentBonusFx';
import type { TalentChanceFx } from './TalentChanceFx';
import type { TalentSynergyFx } from './TalentSynergyFx';

/**
 * Дерево талантов в духе WoW: три пути (урон / здоровье / защита), между способностями — не
 * три одинаковых шарика, а цепочки РАЗНОЙ длины: где-то один талант, где-то три. Все цепочки
 * яруса сходятся в следующую способность.
 *
 * Значения по рангам — СУММАРНЫЕ: [20, 30, 40] значит «+20% → +30% → +40%», а не прибавку к
 * предыдущему рангу.
 *
 * Правило ворот: следующая способность (и метаморфоза) открывается, когда ЛЮБАЯ одна цепочка
 * яруса пройдена целиком — все её таланты прокачаны до максимума.
 *
 * Таланты и способности сохраняются при метаморфозе: паладин владеет и приёмами воина, и рыцаря,
 * и своими. Поэтому в цепочках есть таланты-синергии — они меняют способности, полученные раньше.
 * У правки перка (`modify`) вида нет — она меняет числа способности, а не характеристику.
 */
export type TalentFx = TalentBonusFx | TalentSynergyFx | TalentChanceFx;
