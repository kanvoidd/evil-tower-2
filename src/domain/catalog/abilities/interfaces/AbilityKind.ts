/**
 * Как способность попадает в бой:
 * - `button` — кнопка на поле боя (⚡ цена в ресурсе или золотом);
 * - `passive` — пассивка (🔁): кнопки нет, работает сама;
 * - `basic` — базовое действие линейки (выстрел через карту, удар в спину): кнопки нет,
 *   применяется нажатием по карте и остаётся у всех классов линейки.
 */
export type AbilityKind = 'button' | 'passive' | 'basic';
