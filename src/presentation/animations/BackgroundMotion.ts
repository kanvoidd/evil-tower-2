/**
 * Фоновая часть удара. Карточка бросается к цели, следующее событие начинается в момент касания,
 * а возврат на место доигрывает в фоне. Следующий бросок и шаг героя ждут, пока возврат закончится,
 * иначе карточки накладываются друг на друга.
 */
export class BackgroundMotion {
  private pending: Promise<void> = Promise.resolve();

  /** Дождаться, пока доиграет последнее фоновое движение. */
  settled(): Promise<void> {
    return this.pending;
  }

  /** Запомнить новое фоновое движение — его будет ждать следующее. */
  follow(motion: Promise<void>): void {
    this.pending = motion;
  }
}
